/**
 * Generates supabase/seed.sql, data/foods.json and data/foods.csv from
 * src/data/foods.seed.ts so every format stays in sync.
 * Run: npm run seed:generate
 */
import { writeFileSync } from 'node:fs';
import { CATEGORIES, SEED_FOODS } from '../src/data/foods.seed';
import { toCsv } from '../src/lib/calc/csv';
import { FOOD_CSV_COLUMNS, foodToCsvRow } from '../src/lib/data/foodIO';
import { EXISTING_VEGAN, USDA_UPGRADES, VEG_CATEGORY, VEG_TAG, VEGETARIAN_FOODS } from '../src/data/vegetarian';

const q = (v: string | null) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;

let sql = `-- NutriTrack VN seed data (${SEED_FOODS.length} foods). Generated by scripts/generate-seed.ts – do not edit by hand.\n`;
sql += `-- Records are ESTIMATED unless data_source cites a USDA SR Legacy record (VERIFIED); see data_source on each row.\n\n`;
sql += `insert into public.food_categories (id, code, name_vi, name_en, sort_order) values\n`;
sql += CATEGORIES.map((c) => `(${q(c.id)}, ${q(c.code)}, ${q(c.name_vi)}, ${q(c.name_en)}, ${c.sort_order})`).join(',\n');
sql += `\non conflict (id) do update set code = excluded.code, name_vi = excluded.name_vi, name_en = excluded.name_en, sort_order = excluded.sort_order;\n\n`;

const chunk = 100;
for (let i = 0; i < SEED_FOODS.length; i += chunk) {
  const part = SEED_FOODS.slice(i, i + chunk);
  sql += `insert into public.food_items (food_id, food_name_vi, food_name_en, alternative_names, search_keywords, category, subcategory, calories_kcal, protein_g, carbs_g, fat_g, fiber_g, serving_size, serving_unit, preparation_method, raw_or_cooked, edible_portion, data_source, verification_status, owner_id) values\n`;
  sql += part.map((f) => `(${q(f.food_id)}, ${q(f.food_name_vi)}, ${q(f.food_name_en)}, ${arr(f.alternative_names)}, ${arr(f.search_keywords)}, ${q(f.category)}, ${q(f.subcategory)}, ${f.calories_kcal}, ${f.protein_g}, ${f.carbs_g}, ${f.fat_g}, ${f.fiber_g}, ${f.serving_size}, ${q(f.serving_unit)}, ${q(f.preparation_method)}, ${q(f.raw_or_cooked)}, ${f.edible_portion}, ${q(f.data_source)}, ${q(f.verification_status)}, null)`).join(',\n');
  sql += `\non conflict (food_id) do nothing;\n\n`;
}
const servings = SEED_FOODS.flatMap((f) => f.servings ?? []);
sql += `-- Re-running replaces the global serving sizes of seeded foods only.\ndelete from public.food_servings where owner_id is null and food_id in (${SEED_FOODS.map((f) => q(f.food_id)).join(',')});\n`;
for (let i = 0; i < servings.length; i += 200) {
  sql += `insert into public.food_servings (food_id, label_vi, label_en, grams, is_default, owner_id) values\n`;
  sql += servings.slice(i, i + 200).map((s) => `(${q(s.food_id)}, ${q(s.label_vi)}, ${q(s.label_en)}, ${s.grams}, ${s.is_default}, null)`).join(',\n') + ';\n';
}
writeFileSync('supabase/seed.sql', sql);
writeFileSync('data/foods.json', JSON.stringify(SEED_FOODS.map(({ servings: s, ...f }) => ({ ...f, servings: s?.map(({ label_vi, label_en, grams, is_default }) => ({ label_vi, label_en, grams, is_default })) })), null, 2));
writeFileSync('data/foods.csv', toCsv(SEED_FOODS.map(foodToCsvRow), FOOD_CSV_COLUMNS));

// ---- Migration for databases that already ran seed.sql: vegetarian foods ----
const byId = new Map(SEED_FOODS.map((f) => [f.food_id, f]));
const cols = 'food_id, food_name_vi, food_name_en, alternative_names, search_keywords, category, subcategory, calories_kcal, protein_g, carbs_g, fat_g, fiber_g, serving_size, serving_unit, preparation_method, raw_or_cooked, edible_portion, data_source, verification_status, owner_id';
const row = (f: (typeof SEED_FOODS)[number]) => `(${q(f.food_id)}, ${q(f.food_name_vi)}, ${q(f.food_name_en)}, ${arr(f.alternative_names)}, ${arr(f.search_keywords)}, ${q(f.category)}, ${q(f.subcategory)}, ${f.calories_kcal}, ${f.protein_g}, ${f.carbs_g}, ${f.fat_g}, ${f.fiber_g}, ${f.serving_size}, ${q(f.serving_unit)}, ${q(f.preparation_method)}, ${q(f.raw_or_cooked)}, ${f.edible_portion}, ${q(f.data_source)}, ${q(f.verification_status)}, null)`;
const vegIds = VEGETARIAN_FOODS.map((f) => q(f.food_id)).join(',');
let mig = `-- 0004: vegetarian ("Món chay") foods with cited sources.
-- Generated by scripts/generate-seed.ts from src/data/vegetarian.ts – do not edit by hand.
-- Safe to run more than once. Run it in Supabase › SQL Editor after 0001–0003 and seed.sql.
--   1. adds category P "Món chay";
--   2. adds/updates ${VEGETARIAN_FOODS.length} vegetarian foods (USDA SR Legacy ingredients, dishes calculated from stated recipes);
--   3. replaces ${Object.keys(USDA_UPGRADES).length} existing estimated records with their matching USDA record (now VERIFIED);
--   4. tags existing plant-only foods with the keyword "${VEG_TAG}" so the "Món chay" filter finds them.
begin;

insert into public.food_categories (id, code, name_vi, name_en, sort_order) values
(${q(VEG_CATEGORY.id)}, ${q(VEG_CATEGORY.code)}, ${q(VEG_CATEGORY.name_vi)}, ${q(VEG_CATEGORY.name_en)}, ${VEG_CATEGORY.sort_order})
on conflict (id) do update set code = excluded.code, name_vi = excluded.name_vi, name_en = excluded.name_en, sort_order = excluded.sort_order;

insert into public.food_items (${cols}) values
${VEGETARIAN_FOODS.map(row).join(',\n')}
on conflict (food_id) do update set
  food_name_vi = excluded.food_name_vi, food_name_en = excluded.food_name_en, alternative_names = excluded.alternative_names,
  search_keywords = excluded.search_keywords, category = excluded.category, subcategory = excluded.subcategory,
  calories_kcal = excluded.calories_kcal, protein_g = excluded.protein_g, carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fiber_g = excluded.fiber_g,
  serving_size = excluded.serving_size, serving_unit = excluded.serving_unit, preparation_method = excluded.preparation_method,
  raw_or_cooked = excluded.raw_or_cooked, edible_portion = excluded.edible_portion, data_source = excluded.data_source,
  verification_status = excluded.verification_status, updated_at = now()
where public.food_items.owner_id is null;

`;
for (const id of Object.keys(USDA_UPGRADES)) {
  const f = byId.get(id)!;
  mig += `update public.food_items set calories_kcal = ${f.calories_kcal}, protein_g = ${f.protein_g}, carbs_g = ${f.carbs_g}, fat_g = ${f.fat_g}, fiber_g = ${f.fiber_g}, data_source = ${q(f.data_source)}, verification_status = 'VERIFIED', updated_at = now() where food_id = ${q(id)} and owner_id is null;\n`;
}
mig += `
update public.food_items set search_keywords = array_append(search_keywords, ${q(VEG_TAG)}), updated_at = now()
where owner_id is null and not (${q(VEG_TAG)} = any(search_keywords)) and food_id in (${EXISTING_VEGAN.map(q).join(',')});

delete from public.food_servings where owner_id is null and food_id in (${vegIds});
insert into public.food_servings (food_id, label_vi, label_en, grams, is_default, owner_id) values
${VEGETARIAN_FOODS.flatMap((f) => f.servings ?? []).map((s) => `(${q(s.food_id)}, ${q(s.label_vi)}, ${q(s.label_en)}, ${s.grams}, ${s.is_default}, null)`).join(',\n')};

commit;
`;
writeFileSync('supabase/migrations/0004_vegetarian_foods.sql', mig);
console.log(`Wrote ${SEED_FOODS.length} foods, ${servings.length} servings, and migration 0004 (${VEGETARIAN_FOODS.length} vegetarian foods).`);
